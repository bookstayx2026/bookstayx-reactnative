function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const hideAppChrome =
    /^\/properties\/[^/]+\/?$/.test(pathname) || pathname.startsWith("/owner");

  return (
    <QueryClientProvider client={queryClient}>
      <PwaProvider>
      <div className="min-h-screen bg-[#050709]">
        <div
          className={cn(
            "relative mx-auto min-h-screen w-full max-w-[480px] overflow-x-clip bg-[#050709] shadow-[0_0_80px_rgba(0,0,0,0.8)]",
            hideAppChrome ? "pb-0" : "pb-[108px]",
          )}
        >
          {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
          <Outlet />
        </div>
        {hideAppChrome ? null : <BottomNavigation />}
      </div>
      </PwaProvider>
    </QueryClientProvider>
  );
}
